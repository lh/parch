def clean_truncated_repeats(text, min_text_len=8000, max_period=200,
                            min_period=1, min_repeat_chars=100,
                            min_repeat_times=5):
    """Trim a repeating tail left by a decode loop. Verbatim port of the
    cleaner published on the OvisOCR2 model card."""
    n = len(text)
    if n < min_text_len:
        return text
    max_period = min(max_period, n - 1)
    for unit_len in range(min_period, max_period + 1):
        if text[n - 1] != text[n - 1 - unit_len]:
            continue
        match_len = 1
        idx = n - 2
        while idx >= unit_len and text[idx] == text[idx - unit_len]:
            match_len += 1
            idx -= 1
        total_len = match_len + unit_len
        repeat_times = total_len // unit_len
        tail_len = total_len % unit_len
        if repeat_times >= min_repeat_times and total_len >= min_repeat_chars:
            return text[: n - total_len + unit_len] + text[n - tail_len:]
    return text


def collapse_repeated_blocks(text, min_run=3):
    """Collapse a run of >= min_run consecutive identical blocks to one.

    Greedy decoding can loop on an entire paragraph, whose period is far
    beyond the char-level cleaner's 200-char window. A run of exactly two
    is kept: a document can legitimately repeat a block once, but three or
    more identical consecutive blocks is a decode loop.
    """
    out = []
    run = 0
    for block in text.split("\n\n"):
        if out and block.strip() and block.strip() == out[-1].strip():
            run += 1
            if run == min_run:
                out.pop()
            if run >= min_run:
                continue
        else:
            run = 1
        out.append(block)
    return "\n\n".join(out)


def strip_image_tags(text):
    """Drop the model's <img src="images/bbox_..."> region placeholders;
    parch keeps text only."""
    return "\n\n".join(
        block for block in text.split("\n\n")
        if not block.strip().startswith('<img src="images/bbox_')
    )


