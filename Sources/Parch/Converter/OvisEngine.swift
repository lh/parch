    private let condaPath: String
    private let condaEnv: String
    private let logger: Logger

    init(condaEnv: String = "ovis", logger: Logger) {
        self.condaPath = CondaLocator.find()
        self.condaEnv = condaEnv
        self.logger = logger
    }

    /// Whether conda and the ovis environment appear to be installed.
    static func isAvailable() -> Bool {
        CondaLocator.envExists("ovis")
    }

    /// Convert a single PDF to markdown. Returns the output directory path.
    func convert(pdfPath: String) throws -> String {
        let outputDir = ScanRules.outputDirectory(forPDF: pdfPath)

        guard FileManager.default.fileExists(atPath: condaPath) else {
            throw ConversionError.condaNotFound(condaPath)
        }

        let scriptPath = try materializeWorkerScript()

        let stderrPipe = Pipe()

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/nice")
        process.arguments = [
            "-n", "20",
            condaPath, "run", "--no-capture-output", "-n", condaEnv,
            "python", scriptPath, pdfPath, outputDir,
        ]
        process.qualityOfService = .background
        process.standardOutput = FileHandle.nullDevice
        process.standardError = stderrPipe

        try process.run()
        let stderrData = stderrPipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()

        let stderrOutput = String(data: stderrData, encoding: .utf8) ?? ""

        if process.terminationStatus != 0 {
            throw ConversionError.ovisFailed(
                exitCode: process.terminationStatus,
                stderr: String(stderrOutput.suffix(500))
            )
        }

        // The worker reports per-page timings on stderr; surface them so
        // slow documents can be diagnosed after the fact.
        if !stderrOutput.isEmpty {
            logger.debug("ovis worker for \(pdfPath):\n\(stderrOutput)")
        }

        let expectedMd = ScanRules.markdownPath(forPDF: pdfPath)
        guard FileManager.default.fileExists(atPath: expectedMd) else {
            throw ConversionError.outputNotCreated(expectedMd)
        }

        return outputDir
    }

