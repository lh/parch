/// Converts PDFs with OvisOCR2, a 0.9B page-image-to-markdown model
/// (https://huggingface.co/ATH-MaaS/OvisOCR2), run via a Python worker in a
/// conda environment. Unlike marker it always OCRs the rendered page, so it
/// is most useful for scanned or image-only documents where marker's OCR
/// path is ~3x slower and Vision produces flat, structure-less text.
